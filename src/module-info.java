package basics;

public class ConditionalTest {
    public static void main(String[] args) {

        float temperature = 150;

        if (temperature > 100) {
            System.out.println("Hace mucho calor");
        }

        boolean isAdvancing = true;

        if (isAdvancing) {
            System.out.println("Está avanzando");
        }
    }
}