package basics.oopomodeling.universe;

public class celestialbody {

		public double mass;
		
		protected float radius;
		
		public String name;

		public celestialbody() {
			super();
		}

		public celestialbody(double mass, float radius, String name) {
			super();
			this.mass = mass;
			this.radius = radius;
			this.name = name;
		}
		
		
}
