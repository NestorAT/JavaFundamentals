public class ArithmeticOperators {

	
	public static void main(String[] args) {
		//Decolaration of 2 variables of the same type
		int num1, num2;
		num1 = 234;
		num2= 10;
		
		System.out.println(num1 / num2);
		System.out.println(num1 + num2);
		System.out.println(num1 - num2);
		System.out.println(num1 * num2);

	}
}
